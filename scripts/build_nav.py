"""Generate nav-data.js (navigation data for the extension) from docs/ia/mapping.json, the single source.

Usage: python scripts/build_nav.py           write nav-data.js
       python scripts/build_nav.py --check   fail if nav-data.js is out of date (used by CI)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "nav-data.js"


def strip(obj):
    """Drop documentation-only keys ("_comment", "note") so the shipped data stays small."""
    if isinstance(obj, dict):
        return {k: strip(v) for k, v in obj.items() if not k.startswith("_") and k != "note"}
    if isinstance(obj, list):
        return [strip(v) for v in obj]
    return obj


def build():
    m = json.loads((ROOT / "docs/ia/mapping.json").read_text(encoding="utf-8"))
    keep = ("node", "variants", "read", "fetch", "links", "values", "link", "verify", "form")
    pages = {path: {k: v for k, v in page.items() if k in keep} for path, page in m["pages"].items()}
    data = {
        "structure": strip(m["structure"]),
        "nodes": strip(m["nodes"]),
        "pages": pages,
        "transient": sorted(k for k in m.get("transient_params", {}) if not k.startswith("_")),
        "external": strip(m.get("external", {})),
    }
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return ("// Generated by scripts/build_nav.py from docs/ia/mapping.json. Do not edit by hand.\n"
            "globalThis.insisPlusNav = " + body + ";\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("error: nav-data.js is out of date; run python scripts/build_nav.py")
            sys.exit(1)
        print("ok: nav-data.js is up to date")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.name} ({len(text) // 1024} KB)")
